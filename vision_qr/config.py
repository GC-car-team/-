UART_TX_PIN = 8      # 你的 saoma.py 实测值
UART_RX_PIN = 6      # 你的 saoma.py 实测值
# 注意：TX/RX 要接到主控的 RX/TX（交叉）

# ============================================================
# 帧格式（FROZEN）—— 沿用 saoma.py，主控已适配，不要改
# ============================================================
