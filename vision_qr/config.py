# ============================================================
# 相机
# ============================================================
# QVGA(320x240) vs VGA(640x480)：分辨率直接影响扫码距离，约成正比。
#   QVGA: 80mm 二维码约 0.3~0.4m 可读
#   VGA : 约 0.6m 可读（估算，**必须实测**）
# 你的 saoma.py 原来用 QVGA。如果现场发现要凑很近才能扫到，改 VGA。
FRAMESIZE = "QVGA"       # "QVGA" | "VGA"   改这里即可

SKIP_FRAMES_MS = 2000

# 锁定曝光/增益/白平衡。自动调节会导致"刚才能扫、现在扫不到"
LOCK_EXPOSURE = False    # 打开前先确认固件支持
EXPOSURE_US = 12000      # TBD 亮处调小、暗处调大
LOCK_GAIN = True
LOCK_WHITEBAL = True

# ============================================================
# 解码判定
# ============================================================
# 必须连续 N 帧解出同一结果才锁定并发送。
# 你的 saoma.py 是单帧锁定 —— 一帧误读会被重发 3 秒，若主控 ACK 了，
# 整场比赛就按错误任务跑。这个参数是为此加的。
CONFIRM_FRAMES = 2

# ============================================================
# 语义校验（来自规则，FROZEN）
# ============================================================
# 格式: 4 组三位数，用 + 连接，例如 156+123+516+231
GROUP_COUNT = 4
GROUP_LEN = 3

# 颜色编号: 红=1 黄=2 蓝=3 绿=4 黑=5 浅蓝=6
COLOR_MIN = 1
COLOR_MAX = 6

# 放置位置: 圆环 1-3
POS_MIN = 1
POS_MAX = 3

# 第 1、3 组是颜色，第 2、4 组是位置（索引 0,1,2,3）
GROUP_IS_COLOR = (True, False, True, False)

